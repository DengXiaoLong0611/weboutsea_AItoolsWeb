export function drawingPrompt(style: string) {
  const preset = drawingStyles.find(item => item.id === style);
  if (!preset) throw new Error('无效的手绘画风。');
  return `只编辑上传的这一张原始照片。原照是人物与宠物身份、发型、衣服、配饰、毛色花纹、姿势和物体关系的唯一依据。必须保留原照主体类别、数量和动作，只改变绘画表现方式；原照只有宠物时不要增加人物，原照有人物时保持原人数。目标是可爱的Q版油画棒手绘肖像，只画照片中实际可见的主体部分。若没有清晰可见的人脸，禁止生成人头、人脸、耳朵或头发，不得根据手、衣服、椅背或深色背景推测人物；仅有手时只保留原有手。只有原照清晰可见的人脸才用圆润Q版五官表现；宠物保留原照脸型、耳形、毛色分区和抱着的物品。使用粗而不规则的深黑轮廓、宽厚短笔触、饱满色块、自然叠色和纸白缝隙。避免细密写实毛发、写实照片滤镜、3D、平滑矢量和淡彩铅素描。仅输出一幅纯手绘图，不含文字、水印、签名、拼图或原照缩略图。\n${preset.prompt}`;
}
